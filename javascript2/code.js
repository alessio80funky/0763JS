//関数
//データの処理機です

function Hello(){
    console.log("Hello, World!");
}

Hello();

/*
関数のパーツ

function ->  関数の宣言

Hello -> 関数名

（） -> パラメーター

{ -> 処理の開始

} -> 処理の終了

{} -> 鍵括弧の中に処理を記述する

*/


//別の書き方（アロー関数）

const Hello2 = () => {
    console.log("Hello, World!");
};

