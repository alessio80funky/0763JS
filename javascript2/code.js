//変数・定数

let color = "red"; //変数はletで宣言する ->  中身が変わる可能性があるときに使用します

const color2 = "blue"; //定数はconstで宣言する　-> 中身が変わらないときに使用します

let price = 1000; 
price = 2000; //変数は中身を変更できる ->　再代入という ->  再代入するときはletを使わない

const tax = 1.1; //定数は中身を変更できない ->  再代入できない
//tax = 1.2; //定数は中身を変更できない ->  再代入できないのでエラーになる

console.log(price * tax); //　* -> 演算子

//変数・定数　基本的に同じ名前は再宣言

